#!/usr/bin/env node

import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildPhaserAtlas } from "./lib/build-phaser-atlas.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicRoot = path.join(root, "public/assets/original");
const outputRoot = path.join(publicRoot, "battle-sprite-atlases");
const generatedPath = path.join(root, "src/game/content/battle-sprite-atlases.generated.ts");

async function directoryFrames(directory, prefix = directory) {
  const base = path.join(publicRoot, directory);
  const entries = await readdir(base, { withFileTypes: true });
  const frames = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const relative = `${directory}/${entry.name}`;
    if (entry.isDirectory()) frames.push(...await directoryFrames(relative, prefix));
    else if (entry.name.endsWith(".png")) {
      const framePath = relative.slice(prefix.length + 1).replace(/\.png$/u, "");
      frames.push({
        file: path.join(publicRoot, relative),
        source: `/assets/original/${relative}`,
        name: `${prefix}/${framePath}`,
      });
    }
  }
  return frames;
}

const rootFrameNames = [
  "turn-transition-player.png",
  "turn-transition-enemy.png",
  "turn-transition-shadow.png",
  ...Array.from({ length: 6 }, (_, frame) =>
    `turn-transition-dust-${String(frame).padStart(2, "0")}.png`),
];
const atlasInputs = [
  { id: "map-combat", frames: await directoryFrames("map-combat") },
  {
    id: "turn-transition",
    frames: rootFrameNames.map((file) => ({
      file: path.join(publicRoot, file),
      source: `/assets/original/${file}`,
      name: `turn-transition/${file.replace(/^turn-transition-/u, "").replace(/\.png$/u, "")}`,
    })),
  },
  { id: "stage4-force-field-pulse", frames: await directoryFrames("stage4-force-field-pulse") },
  { id: "stage26-column-push", frames: await directoryFrames("stage26-column-push") },
];

await rm(outputRoot, { recursive: true, force: true });
await mkdir(outputRoot, { recursive: true });
const generatedAtlases = [];
const generatedFrames = {};
for (const input of atlasInputs) {
  const atlas = await buildPhaserAtlas({
    id: input.id,
    frames: input.frames,
    maxWidth: 1024,
    maxHeight: 1024,
  });
  const image = `/assets/original/battle-sprite-atlases/${input.id}.png`;
  const data = `/assets/original/battle-sprite-atlases/${input.id}.json`;
  await Promise.all([
    writeFile(path.join(outputRoot, `${input.id}.png`), atlas.png),
    writeFile(path.join(outputRoot, `${input.id}.json`), `${JSON.stringify(atlas.json)}\n`, "utf8"),
  ]);
  generatedAtlases.push({
    id: input.id,
    textureKey: `battle-sprite-${input.id}`,
    image,
    data,
    width: atlas.width,
    height: atlas.height,
    decodedBytes: atlas.decodedBytes,
    frameCount: atlas.frames.length,
  });
  for (const frame of atlas.frames) {
    generatedFrames[frame.source] = { atlas: input.id, frame: frame.name };
  }
}

const generatedSource = `// Generated by scripts/generate-battle-sprite-atlases.mjs.\n`
  + `// Do not hand-edit.\n`
  + `export const BATTLE_SPRITE_ATLASES = ${JSON.stringify(generatedAtlases, null, 2)} as const;\n\n`
  + `export const BATTLE_SPRITE_ATLAS_FRAMES = ${JSON.stringify(generatedFrames, null, 2)} as const;\n`;
await writeFile(generatedPath, generatedSource, "utf8");

console.log(`battle-sprite atlases: ${generatedAtlases.length} atlases, ${Object.keys(generatedFrames).length} frames`);
for (const atlas of generatedAtlases) {
  console.log(`  ${atlas.id}: ${atlas.frameCount} frames, ${atlas.width}x${atlas.height}, ${(atlas.decodedBytes / 1024 / 1024).toFixed(2)} MiB decoded`);
}
