#!/usr/bin/env node

import { readdir, readFile, mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { decodeRgbaPng, encodeRgbaPng } from "./lib/png-atlas.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.join(root, "public/assets/original/map-actions");
const outputRoot = path.join(root, "public/assets/original/map-action-atlases");
const generatedPath = path.join(root, "src/game/content/map-action-atlases.generated.ts");
const atlasIds = [
  "shoot",
  "fire-1", "fire-2", "fire-3", "fire-4",
  "heal-1", "heal-2", "heal-3",
  "lightning-1", "lightning-2", "lightning-3", "lightning-4",
  "ice-1", "recovery-1", "attack-up", "defense-up",
  "poison", "confusion", "attack-down", "defense-down", "spell-seal", "dispel",
  "stomp-1", "stomp-2", "stomp-3", "wd",
];
const atlasMaxWidth = 1024;
const atlasPadding = 2;

async function collectPngFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await collectPngFiles(target));
    else if (/\.png$/iu.test(entry.name)) files.push(target);
  }
  return files.sort();
}

function frameName(atlasId, file) {
  const relative = path.relative(path.join(sourceRoot, atlasId), file)
    .split(path.sep)
    .join("/")
    .replace(/\.png$/iu, "");
  return `${atlasId}__${relative.replaceAll("/", "__")}`;
}

function sourceUrl(atlasId, file) {
  const relative = path.relative(path.join(sourceRoot, atlasId), file)
    .split(path.sep)
    .join("/");
  return `/assets/original/map-actions/${atlasId}/${relative}`;
}

function placeFrames(frames) {
  let x = atlasPadding;
  let y = atlasPadding;
  let rowHeight = 0;
  let atlasWidth = atlasPadding;
  const placements = [];
  for (const frame of frames) {
    const width = frame.image.width;
    const height = frame.image.height;
    if (x > atlasPadding && x + width + atlasPadding > atlasMaxWidth) {
      x = atlasPadding;
      y += rowHeight + atlasPadding;
      rowHeight = 0;
    }
    placements.push({ ...frame, x, y });
    x += width + atlasPadding;
    rowHeight = Math.max(rowHeight, height);
    atlasWidth = Math.max(atlasWidth, x);
  }
  const atlasHeight = y + rowHeight + atlasPadding;
  return {
    width: atlasWidth,
    height: atlasHeight,
    placements,
  };
}

function copyPixels(target, targetWidth, source, x, y) {
  for (let row = 0; row < source.height; row += 1) {
    source.pixels.copy(
      target,
      ((y + row) * targetWidth + x) * 4,
      row * source.width * 4,
      (row + 1) * source.width * 4,
    );
  }
}

const generatedAtlases = [];
await rm(outputRoot, { recursive: true, force: true });
await mkdir(outputRoot, { recursive: true });
for (const atlasId of atlasIds) {
  const files = await collectPngFiles(path.join(sourceRoot, atlasId));
  if (files.length === 0) throw new Error(`map action atlas ${atlasId} has no PNG frames`);
  const frames = await Promise.all(files.map(async (file) => ({
    file,
    source: sourceUrl(atlasId, file),
    name: frameName(atlasId, file),
    bytes: await readFile(file),
  })));
  for (const frame of frames) {
    frame.image = decodeRgbaPng(frame.bytes, path.relative(root, frame.file));
  }
  const packed = placeFrames(frames);
  const pixels = Buffer.alloc(packed.width * packed.height * 4);
  for (const frame of packed.placements) copyPixels(pixels, packed.width, frame.image, frame.x, frame.y);
  const imageName = `${atlasId}.png`;
  const dataName = `${atlasId}.json`;
  const jsonFrames = Object.fromEntries(packed.placements.map((frame) => [frame.name, {
    frame: { x: frame.x, y: frame.y, w: frame.image.width, h: frame.image.height },
    rotated: false,
    trimmed: false,
    spriteSourceSize: { x: 0, y: 0, w: frame.image.width, h: frame.image.height },
    sourceSize: { w: frame.image.width, h: frame.image.height },
  }]));
  const json = { frames: jsonFrames };
  const atlasPng = encodeRgbaPng(packed.width, packed.height, pixels);
  await Promise.all([
    writeFile(path.join(outputRoot, imageName), atlasPng),
    writeFile(path.join(outputRoot, dataName), `${JSON.stringify(json)}\n`, "utf8"),
  ]);
  generatedAtlases.push({
    id: atlasId,
    textureKey: `map-action-${atlasId}`,
    image: `/assets/original/map-action-atlases/${imageName}`,
    data: `/assets/original/map-action-atlases/${dataName}`,
    frameCount: frames.length,
    sourceBytes: frames.reduce((sum, frame) => sum + frame.bytes.length, 0),
    atlasBytes: atlasPng.length,
  });
}

const generatedSource = `// Generated by scripts/generate-map-action-atlases.mjs.\n// Do not hand-edit.\nexport const MAP_ACTION_ATLAS_IDS = ${JSON.stringify(atlasIds)} as const;\n\nexport const MAP_ACTION_ATLASES = ${JSON.stringify(generatedAtlases.map(({ frameCount: _frameCount, sourceBytes: _sourceBytes, atlasBytes: _atlasBytes, ...atlas }) => atlas), null, 2)} as const;\n`;
await writeFile(generatedPath, generatedSource, "utf8");

const sourceBytes = generatedAtlases.reduce((sum, atlas) => sum + atlas.sourceBytes, 0);
const atlasBytes = generatedAtlases.reduce((sum, atlas) => sum + atlas.atlasBytes, 0);
console.log(`map-action atlases: ${generatedAtlases.length} atlases, ${generatedAtlases.reduce((sum, atlas) => sum + atlas.frameCount, 0)} frames`);
console.log(`  PNG bytes: ${(sourceBytes / 1024 / 1024).toFixed(2)} MiB -> ${(atlasBytes / 1024 / 1024).toFixed(2)} MiB (atlas images and JSON are separate)`);
