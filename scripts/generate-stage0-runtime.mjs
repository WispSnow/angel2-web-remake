#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import iconv from "iconv-lite";

const root = path.resolve(import.meta.dirname, "..");
const templatePath = path.join(root, "reverse/decoded/B/0001/00.raw");
const terrainMappingPath = path.join(root, "reverse/parsed/native/terrain-token-map.json");
const hudPresentationPath = path.join(root, "reverse/parsed/native/hud-presentations.json");
const outputPath = path.join(root, "src/game/content/stage0-runtime.generated.ts");
const planarAssetPath = path.join(root, "reverse/renders/planar/A");
const portraitAssetPath = path.join(root, "reverse/renders/planar/D");
const publicAssetPath = path.join(root, "public/assets/original");
const publicStatusIconPath = path.join(publicAssetPath, "status-icons");
const convertedEffectPath = path.join(root, "reverse/converted/audio/wav/E");
const publicEffectPath = path.join(publicAssetPath, "audio/e");
const stage0EffectRecords = [0, 2, 11, 14, 38, 51];
const battleChromeAssets = {
  "battle-chrome-top.png": "00.png",
  "battle-chrome-corner-left.png": "01.png",
  "battle-chrome-corner-right.png": "02.png",
  "battle-chrome-glass.png": "03.png",
  "battle-chrome-side-left.png": "04.png",
  "battle-chrome-side-right.png": "05.png",
  "battle-chrome-bottom-left.png": "06.png",
  "battle-chrome-bottom-right.png": "07.png",
};
const nativeCursorAssets = {
  "command-menu-pointer.png": "00.png",
  "native-cursor-up.png": "01.png",
  "native-cursor-down.png": "02.png",
  "native-cursor-left.png": "03.png",
  "native-cursor-right.png": "04.png",
};
const commandMenuAssets = {
  "command-menu-top.png": "05.png",
  "command-menu-side.png": "06.png",
  "command-menu-bottom.png": "07.png",
  "command-menu-selection.png": "08.png",
};
const tacticalPanelToggleAssets = {
  "tactical-panel-battle-animation-off.png": "20.png",
  "tactical-panel-battle-animation-on.png": "21.png",
  "tactical-panel-grid-off.png": "24.png",
  "tactical-panel-grid-on.png": "25.png",
  "tactical-panel-edge-scroll-off.png": "26.png",
  "tactical-panel-edge-scroll-on.png": "27.png",
  "tactical-panel-portraits-off.png": "30.png",
  "tactical-panel-portraits-on.png": "31.png",
};
const turnTransitionAssets = {
  "turn-transition-player.png": "0019/00.png",
  "turn-transition-enemy.png": "0019/01.png",
  "turn-transition-shadow.png": "0019/02.png",
  ...Object.fromEntries(Array.from({ length: 6 }, (_, frame) => [
    `turn-transition-dust-${String(frame).padStart(2, "0")}.png`,
    `0026/${String(frame).padStart(2, "0")}.png`,
  ])),
};

const [template, mappingDocument, hudPresentation, ...dialogueDocuments] = await Promise.all([
  readFile(templatePath),
  readFile(terrainMappingPath, "utf8").then(JSON.parse),
  readFile(hudPresentationPath, "utf8").then(JSON.parse),
  ...[0, 1, 2, 3].map((record) => readFile(
    path.join(root, `reverse/parsed/dialogue/${String(record).padStart(4, "0")}.json`),
    "utf8",
  ).then(JSON.parse)),
]);

if (hudPresentation.format !== "ANGEL2 hovered-unit HUD presentation specification"
  || hudPresentation.sidePanelChrome?.resource !== "A/6"
  || hudPresentation.sidePanelChrome.frames?.length !== 15) {
  throw new Error("hud-presentations.json lacks the verified A/6 side-panel chrome contract");
}

if (template.length !== 8506) {
  throw new Error(`B/0001 expected 8506 bytes, got ${template.length}`);
}

const stage = mappingDocument.stages.find((entry) => entry.stage === 0);
if (!stage) throw new Error("terrain mapping has no stage 0");

const terrain = template.subarray(256, 2756);
const tokenToSlot = new Uint8Array(128).fill(0);
for (const mapping of stage.configuredMappings) {
  tokenToSlot[mapping.token] = mapping.logicalSlot;
}

const encode = (bytes) => Buffer.from(bytes).toString("base64");
const speechRecordByCharacter = Object.fromEntries(
  [...new Set(dialogueDocuments.flatMap((document) =>
    document.actions.filter((action) => action.op === "text").flatMap((action) => [...action.text])))]
    .filter((character) => /[^\x00-\x7f]/u.test(character) && !/[，．？！「」\s]/u.test(character))
    .map((character) => {
      const encoded = iconv.encode(character, "big5");
      const numericBig5 = encoded.length >= 2 ? encoded.readUInt16BE(0) : encoded[0];
      return [character, 57 + numericBig5 % 15];
    }),
);
const source = `// Generated by scripts/generate-stage0-runtime.mjs from decoded B/0001.\n` +
  `// Do not hand-edit: regenerate after the evidence pipeline changes.\n` +
  `export const STAGE0_TERRAIN_TOKENS_BASE64 = ${JSON.stringify(encode(terrain))};\n` +
  `export const STAGE0_TOKEN_TO_SLOT_BASE64 = ${JSON.stringify(encode(tokenToSlot))};\n` +
  `export const STAGE0_SPEECH_RECORD_BY_CHARACTER: Readonly<Record<string, number>> = ${JSON.stringify(speechRecordByCharacter)};\n`;

await writeFile(outputPath, source, "utf8");

await mkdir(publicAssetPath, { recursive: true });
await mkdir(publicEffectPath, { recursive: true });
await mkdir(publicStatusIconPath, { recursive: true });
await Promise.all([
  copyFile(path.join(planarAssetPath, "0002/00.png"), path.join(publicAssetPath, "unit-ally-soldier.png")),
  copyFile(path.join(planarAssetPath, "0002/20.png"), path.join(publicAssetPath, "unit-ally-archer.png")),
  copyFile(path.join(planarAssetPath, "0002/22.png"), path.join(publicAssetPath, "unit-ally-cavalry.png")),
  copyFile(path.join(planarAssetPath, "0002/24.png"), path.join(publicAssetPath, "unit-ally-sister.png")),
  copyFile(path.join(planarAssetPath, "0002/28.png"), path.join(publicAssetPath, "unit-ally-warrior.png")),
  copyFile(path.join(portraitAssetPath, "0015/00.png"), path.join(publicAssetPath, "portrait-hading.png")),
  ...stage0EffectRecords.map((record) => copyFile(
    path.join(convertedEffectPath, `${String(record).padStart(4, "0")}.wav`),
    path.join(publicEffectPath, `${String(record).padStart(2, "0")}.wav`),
  )),
  ...Object.entries(battleChromeAssets).map(([output, source]) =>
    copyFile(path.join(planarAssetPath, "0000", source), path.join(publicAssetPath, output))),
  ...Object.entries(tacticalPanelToggleAssets).map(([output, source]) =>
    copyFile(path.join(planarAssetPath, "0006", source), path.join(publicAssetPath, output))),
  ...Object.entries(turnTransitionAssets).map(([output, source]) =>
    copyFile(path.join(planarAssetPath, source), path.join(publicAssetPath, output))),
  ...Array.from({ length: 8 }, (_, frame) => copyFile(
    path.join(planarAssetPath, "0017", `${String(frame).padStart(2, "0")}.png`),
    path.join(publicStatusIconPath, `${String(frame).padStart(2, "0")}.png`),
  )),
]);

// ImageMagick 默认往 PNG 里写 tIME 与 date:create/modify/timestamp 文本块，
// 那会让同样的像素每次生成都产生不同字节，掩盖真正的素材改动。排除日期块后
// 重跑生成器只在像素真的变化时才产生 diff。
function runMagick(args) {
  execFileSync("magick", ["-define", "png:exclude-chunk=date,time", ...args]);
}

// A/0001 uses palette index 0 as the native transparent compositing color.
// The planar audit renders retain that index as opaque black, so the native
// pointer set and every menu part restore that alpha before browser compositing.
for (const [output, source] of Object.entries({ ...nativeCursorAssets, ...commandMenuAssets })) {
  runMagick([
    path.join(planarAssetPath, "0001", source),
    "-transparent", "#000000",
    path.join(publicAssetPath, output),
  ]);
}

function copyAlphaMask(colorFrame, maskFrame, output) {
  runMagick([
    colorFrame,
    "(", maskFrame, "-alpha", "extract", ")",
    "-alpha", "off",
    "-compose", "CopyOpacity",
    "-composite",
    output,
  ]);
}

function composeStatueForeground(output, firstFrame, xOffsets) {
  const widths = [16, 24, 32, 16, 24];
  const heights = [15, 44, 44, 44, 44];
  const args = ["-size", "32x191", "canvas:none"];
  let y = 0;
  for (let index = 0; index < heights.length; index += 1) {
    const frame = String(firstFrame + index).padStart(2, "0");
    args.push(
      path.join(planarAssetPath, "0005", `${frame}.png`),
      "-geometry", `+${xOffsets[index]}+${y}`,
      "-composite",
    );
    y += heights[index];
  }
  if (y !== 191 || xOffsets.some((x, index) => x + widths[index] > 32)) {
    throw new Error("invalid A/0005 statue foreground layout");
  }
  args.push(output);
  runMagick(args);
}

function composeTacticalPanelFoundation(output) {
  // B7C6 draws frame 19, followed by release-initial frame 29 at (584,39)
  // and frame 22 at (528,77). The four player setting patches stay separate
  // because the browser must replace them whenever their live state changes.
  runMagick([
    path.join(planarAssetPath, "0006/19.png"),
    path.join(planarAssetPath, "0006/29.png"),
    "-geometry", "+104+39",
    "-composite",
    path.join(planarAssetPath, "0006/22.png"),
    "-geometry", "+48+77",
    "-composite",
    output,
  ]);
}

const gameplayPalette = hudPresentation.resourceValidation.paletteColors.map(
  ([red, green, blue]) => `#${[red, green, blue].map((value) => value.toString(16).padStart(2, "0")).join("")}`,
);
function hudChromeFrame(frame) {
  const graphic = hudPresentation.sidePanelChrome.frames.find(
    (candidate) => candidate.imageIndex === frame,
  );
  if (!graphic) throw new Error(`missing verified A/6/${frame} HUD chrome frame`);
  return path.join(root, graphic.path);
}

function appendComposite(args, frame, x, y) {
  args.push(hudChromeFrame(frame), "-geometry", `+${x}+${y}`, "-composite");
}

function appendRepeatedComposite(args, frame, x, y, stepX, stepY, repeats) {
  for (let index = 0; index < repeats; index += 1) {
    appendComposite(args, frame, x + stepX * index, y + stepY * index);
  }
}

function composeUnitTopChrome(output) {
  const args = ["-size", "160x149", "canvas:none"];
  const rectangles = [
    [0, 7, 1, 135, 14], [1, 7, 1, 135, 0], [2, 7, 1, 135, 11], [3, 7, 1, 135, 14], [4, 7, 1, 135, 0],
    [155, 7, 1, 135, 0], [156, 7, 1, 135, 14], [157, 7, 1, 135, 11], [158, 7, 1, 135, 0], [159, 7, 1, 135, 14],
    [125, 7, 12, 102, 0], [127, 8, 11, 101, 7], [126, 8, 10, 100, 2],
    [138, 7, 12, 102, 0], [140, 8, 11, 101, 7], [139, 8, 10, 100, 2],
    [8, 8, 112, 1, 14], [8, 9, 112, 1, 0],
  ];
  for (const [x, y, width, height, colorIndex] of rectangles) {
    args.push("-fill", gameplayPalette[colorIndex], "-draw", `rectangle ${x},${y} ${x + width - 1},${y + height - 1}`);
  }
  appendRepeatedComposite(args, 1, 7, 0, 8, 0, 20);
  appendRepeatedComposite(args, 0, 7, 143, 8, 0, 20);
  for (const [x, y] of [[0, 0], [0, 142], [153, 0], [153, 142]]) appendComposite(args, 5, x, y);
  appendRepeatedComposite(args, 6, 8, 8, 0, 7, 16);
  appendRepeatedComposite(args, 7, 115, 8, 0, 7, 16);
  appendRepeatedComposite(args, 3, 8, 114, 8, 0, 13);
  appendComposite(args, 2, 8, 114);
  appendComposite(args, 4, 112, 114);
  appendComposite(args, 8, 56, 113);
  appendComposite(args, 14, 120, 113);
  args.push(output);
  runMagick(args);
}

function composeUnitBodyFrame(output) {
  const args = ["-size", "160x171", "canvas:none"];
  const drawRectangle = (x, y, width, height, colorIndex) => {
    args.push("-fill", gameplayPalette[colorIndex], "-draw", `rectangle ${x},${y} ${x + width - 1},${y + height - 1}`);
  };
  drawRectangle(0, 0, 160, 2, 14);
  drawRectangle(0, 0, 2, 171, 14);
  drawRectangle(158, 0, 2, 171, 14);
  drawRectangle(0, 169, 160, 2, 14);
  for (const y of [1, 22, 43, 64, 85]) {
    drawRectangle(0, y, 160, 1, 14);
    drawRectangle(2, y + 1, 156, 1, 0);
    drawRectangle(2, y + 1, 1, 20, 0);
    drawRectangle(157, y + 1, 1, 20, 0);
    drawRectangle(2, y + 20, 156, 1, 15);
  }
  drawRectangle(0, 106, 160, 1, 14);
  drawRectangle(2, 107, 156, 1, 0);
  drawRectangle(2, 107, 1, 63, 0);
  drawRectangle(157, 107, 1, 63, 0);
  args.push(output);
  runMagick(args);
}

function composeMinimapFrame(output) {
  const args = ["-size", "160x171", "canvas:none"];
  appendComposite(args, 9, 0, 0);
  appendRepeatedComposite(args, 6, 0, 10, 0, 7, 22);
  appendRepeatedComposite(args, 7, 155, 10, 0, 7, 22);
  appendComposite(args, 10, 0, 161);
  args.push(output);
  runMagick(args);
}

function composeRoundFrame(output) {
  const args = ["-size", "160x28", "canvas:none"];
  appendRepeatedComposite(args, 12, 0, 0, 8, 0, 18);
  appendComposite(args, 11, 0, 0);
  appendComposite(args, 13, 144, 0);
  args.push(output);
  runMagick(args);
}

composeTacticalPanelFoundation(path.join(publicAssetPath, "tactical-panel.png"));
composeUnitTopChrome(path.join(publicAssetPath, "hud-unit-top-chrome.png"));
composeUnitBodyFrame(path.join(publicAssetPath, "hud-unit-body-frame.png"));
composeMinimapFrame(path.join(publicAssetPath, "hud-minimap-frame.png"));
composeRoundFrame(path.join(publicAssetPath, "hud-round-frame.png"));

// A/0003 carries the enemy colors but no stored mask. The same-pose A/0002
// frames provide the exact map-sprite alpha used by the native compositor.
copyAlphaMask(
  path.join(planarAssetPath, "0003/00.png"),
  path.join(planarAssetPath, "0002/00.png"),
  path.join(publicAssetPath, "unit-enemy-soldier.png"),
);
copyAlphaMask(
  path.join(planarAssetPath, "0003/22.png"),
  path.join(planarAssetPath, "0002/22.png"),
  path.join(publicAssetPath, "unit-enemy-cavalry.png"),
);

// A/0000 only contains the opaque 40px side strips. A/0005 supplies the
// transparent portions that the native renderer stacks over the map in five
// consecutive scanline bands (15 + 44 * 4 = 191px).
composeStatueForeground(
  path.join(publicAssetPath, "battle-statue-left-foreground.png"),
  0,
  [0, 0, 0, 0, 0],
);
composeStatueForeground(
  path.join(publicAssetPath, "battle-statue-right-foreground.png"),
  5,
  [16, 8, 0, 16, 8],
);

console.log(`wrote ${path.relative(root, outputPath)} (${terrain.length} terrain cells)`);
console.log("wrote stage 0 battle chrome/statue foreground, native cursors/command-menu chrome, stateful tactical panel, side-panel chrome, turn-transition graphics, map sprites and ordinary-combat VOC assets");
