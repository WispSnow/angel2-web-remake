#!/usr/bin/env node

import { createHash } from "node:crypto";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const reverseRoot = (...parts) => path.join(root, "reverse", ...parts);
const outputPath = path.join(root, "src/game/content/credits-runtime.generated.ts");
const assetRoot = path.join(root, "public/assets/original/credits");
const sourcePath = reverseRoot("parsed/native/ending-presentations.json");
const sourceBytes = await readFile(sourcePath);
const source = JSON.parse(sourceBytes.toString("utf8"));
const presentation = source.module46CreditsAndTerminalScreen;
const sourceHash = createHash("sha256").update(sourceBytes).digest("hex");
const musicResource = source.resources.find(({ container, record }) =>
  container === "UN" && record === 55);
if (!musicResource || musicResource.role !== "module-46 credits music data") {
  throw new Error("ending evidence is missing module 46 UN/55 music");
}
if (presentation.transitionAfterPages.calls !== presentation.pages.length + 1
  || presentation.transitionAfterPages.inputSkipCheck !== false) {
  throw new Error("ending evidence no longer describes seven pages plus one unskippable transition");
}

const roleFrames = presentation.roleFrames.map(({ frame, text }) => ({
  frame,
  text,
  src: `/assets/original/credits/roles/${String(frame).padStart(2, "0")}.png`,
}));
const nameFrames = presentation.nameFrames.map(({ frame, text }) => ({
  frame,
  text,
  src: `/assets/original/credits/names/${String(frame).padStart(2, "0")}.png`,
}));
const pages = presentation.pages.map(({ page, frames }) => ({ page, frames }));
const finalScreen = {
  base: "/assets/original/credits/end/00.png",
  overlays: [1, 2, 3, 4].map((frame) => `/assets/original/credits/end/${String(frame).padStart(2, "0")}.png`),
};
const finalTimeline = [];
let pendingWaitNativeTicks = 0;
const appendFinalOperation = (operation) => {
  if (operation.op === "wait") {
    pendingWaitNativeTicks += operation.nativeTicks;
    return;
  }
  if (operation.op === "repeat") {
    for (let iteration = 0; iteration < operation.times; iteration += 1) {
      for (const child of operation.body) appendFinalOperation(child);
    }
    return;
  }
  if (operation.op !== "draw") throw new Error(`unknown module 46 final operation ${operation.op}`);
  if (finalTimeline.length === 0 && pendingWaitNativeTicks > 0) {
    finalTimeline.push({ frame: null, waitNativeTicks: pendingWaitNativeTicks });
  } else if (pendingWaitNativeTicks > 0) {
    finalTimeline[finalTimeline.length - 1].waitNativeTicks += pendingWaitNativeTicks;
  }
  pendingWaitNativeTicks = 0;
  finalTimeline.push({ frame: operation.frame, waitNativeTicks: 0 });
};
for (const operation of presentation.finalScreen.outerLoop) appendFinalOperation(operation);
if (pendingWaitNativeTicks > 0 && finalTimeline.length > 0) {
  finalTimeline[finalTimeline.length - 1].waitNativeTicks += pendingWaitNativeTicks;
}
if (!presentation.finalScreen.repeatsForever || presentation.finalScreen.inputExitCheck !== false) {
  throw new Error("ending evidence no longer describes a permanent noninteractive final loop");
}
const transition = {
  count: presentation.transitionAfterPages.calls,
  nativeSteps: 400,
  waitNativeTicksPerStep: 2,
  inputSkippable: presentation.transitionAfterPages.inputSkipCheck,
};
const music = {
  track: "UN/55",
  source: "/assets/original/credits/music.wav",
  sourceSha256: musicResource.sha256,
};
const generated = `// Generated by scripts/generate-credits-runtime.mjs from ending-presentations.json.\n// Do not hand-edit: regenerate after the evidence pipeline changes.\n\n`
  + `export const CREDITS_CONTENT_IDENTITY = ${JSON.stringify(`credits/module46-${sourceHash}`)} as const;\n`
  + `export const CREDITS_ROLE_FRAMES = ${JSON.stringify(roleFrames)} as const;\n`
  + `export const CREDITS_NAME_FRAMES = ${JSON.stringify(nameFrames)} as const;\n`
  + `export const CREDITS_PAGES = ${JSON.stringify(pages)} as const;\n`
  + `export const CREDITS_TRANSITION = ${JSON.stringify(transition)} as const;\n`
  + `export const CREDITS_MUSIC = ${JSON.stringify(music)} as const;\n`
  + `export const CREDITS_FINAL_SCREEN = ${JSON.stringify(finalScreen)} as const;\n`
  + `export const CREDITS_FINAL_TIMELINE = ${JSON.stringify(finalTimeline)} as const;\n`;
await writeFile(outputPath, generated, "utf8");

const copySet = [];
for (const frame of roleFrames) copySet.push([reverseRoot("renders/planar/B/0088", `${String(frame.frame).padStart(2, "0")}.png`), path.join(assetRoot, "roles", `${String(frame.frame).padStart(2, "0")}.png`)]);
for (const frame of nameFrames) copySet.push([reverseRoot("renders/planar/C/0033", `${String(frame.frame).padStart(2, "0")}.png`), path.join(assetRoot, "names", `${String(frame.frame).padStart(2, "0")}.png`)]);
for (let frame = 0; frame < 5; frame += 1) copySet.push([reverseRoot("renders/planar/UN/0054", `${String(frame).padStart(2, "0")}.png`), path.join(assetRoot, "end", `${String(frame).padStart(2, "0")}.png`)]);
copySet.push([
  reverseRoot("converted/audio/rix-wav/UN/0055.wav"),
  path.join(assetRoot, "music.wav"),
]);
await Promise.all(copySet.map(async ([sourceFile, destination]) => {
  await mkdir(path.dirname(destination), { recursive: true });
  await copyFile(sourceFile, destination);
}));
console.log(`wrote ${path.relative(root, outputPath)} (7 pages, terminal loop)`);
