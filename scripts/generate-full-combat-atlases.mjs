#!/usr/bin/env node

import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildPhaserAtlas } from "./lib/build-phaser-atlas.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.join(root, "public/assets/original/full-combat");
const outputRoot = path.join(root, "public/assets/original/full-combat-atlases");
const generatedPath = path.join(root, "src/game/content/full-combat-atlases.generated.ts");

const entries = await readdir(sourceRoot, { withFileTypes: true });
const groups = new Map();
for (const entry of entries) {
  if (!entry.isDirectory() || entry.name === "backgrounds") continue;
  if (entry.name === "common-trail") {
    groups.set("common-trail", [{ directory: entry.name, set: "trail" }]);
    continue;
  }
  const match = /^(left|right)-(.+)-(direct|plus50)$/u.exec(entry.name);
  if (!match) throw new Error(`unrecognized full-combat frame directory ${entry.name}`);
  const [, side, classId, set] = match;
  const id = `${side}-${classId}`;
  const group = groups.get(id) ?? [];
  group.push({ directory: entry.name, side, classId, set });
  groups.set(id, group);
}

await rm(outputRoot, { recursive: true, force: true });
await mkdir(outputRoot, { recursive: true });
const generatedAtlases = [];
const generatedFrames = {};

for (const [id, directories] of [...groups.entries()].sort(([left], [right]) => left.localeCompare(right))) {
  const frames = [];
  for (const directory of directories.sort((left, right) => left.set.localeCompare(right.set))) {
    const files = (await readdir(path.join(sourceRoot, directory.directory)))
      .filter((file) => file.endsWith(".png"))
      .sort();
    for (const file of files) {
      const index = file.replace(/\.png$/u, "");
      const name = id === "common-trail"
        ? `common/trail/${index}`
        : `${directory.side}/${directory.classId}/${directory.set}/${index}`;
      frames.push({
        file: path.join(sourceRoot, directory.directory, file),
        source: `/assets/original/full-combat/${directory.directory}/${file}`,
        name,
      });
    }
  }
  // 女帝的 side-1 records are native zero placeholders. The source
  // directories deliberately exist but contain no drawable frames.
  if (frames.length === 0) continue;

  const atlas = await buildPhaserAtlas({ id, frames, maxWidth: 1024, maxHeight: 1024 });
  const image = `/assets/original/full-combat-atlases/${id}.png`;
  const data = `/assets/original/full-combat-atlases/${id}.json`;
  await Promise.all([
    writeFile(path.join(outputRoot, `${id}.png`), atlas.png),
    writeFile(path.join(outputRoot, `${id}.json`), `${JSON.stringify(atlas.json)}\n`, "utf8"),
  ]);
  generatedAtlases.push({
    id,
    image,
    data,
    width: atlas.width,
    height: atlas.height,
    decodedBytes: atlas.decodedBytes,
    frameCount: atlas.frames.length,
  });
  for (const frame of atlas.frames) {
    generatedFrames[frame.name] = {
      atlas: id,
      x: frame.x,
      y: frame.y,
      width: frame.width,
      height: frame.height,
    };
  }
}

const generatedSource = `// Generated by scripts/generate-full-combat-atlases.mjs.\n`
  + `// Do not hand-edit.\n`
  + `export const FULL_COMBAT_ATLASES = ${JSON.stringify(generatedAtlases, null, 2)} as const;\n\n`
  + `export const FULL_COMBAT_ATLAS_FRAMES = ${JSON.stringify(generatedFrames, null, 2)} as const;\n`;
await writeFile(generatedPath, generatedSource, "utf8");

const atlasBytes = generatedAtlases.reduce((sum, atlas) => sum + atlas.decodedBytes, 0);
console.log(`full-combat atlases: ${generatedAtlases.length} atlases, ${Object.keys(generatedFrames).length} frames`);
console.log(`  largest decoded atlas: ${(Math.max(...generatedAtlases.map(({ decodedBytes }) => decodedBytes)) / 1024 / 1024).toFixed(2)} MiB; total decoded canvases: ${(atlasBytes / 1024 / 1024).toFixed(2)} MiB`);
