#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const unitCatalogPath = path.join(root, "reverse/parsed/native/unit-catalog.json");
const mapRulesPath = path.join(root, "reverse/parsed/native/map-rules.json");
const promotionTablePath = path.join(root, "reverse/parsed/native/promotion-table.json");
const campaignRosterPath = path.join(root, "reverse/parsed/native/campaign-roster.json");
const outputPath = path.join(root, "src/game/content/class-catalog.generated.ts");
const promotionDialogueOutputPath = path.join(
  root,
  "src/game/content/promotion-dialogue.generated.ts",
);

const CLASS_IDS = [
  "soldier",
  "magic-sword-warrior",
  "jungle-warrior",
  "magic-priest",
  "prayer-guide",
  "curse-master",
  "magician",
  "great-axe-warrior",
  "half-dragon-warrior",
  "magic-armor-warrior",
  "magic-guide",
  "evil-mage",
  "magic-archer",
  "land-knight",
  "demon-dragon-knight",
  "flying-dragon-knight",
  "beast-knight",
  "bone-knight",
  "swift-dragon-knight",
  "great-dragon-knight",
  "archer",
  "crossbow",
  "cavalry",
  "pegasus-warrior",
  "sister",
  "monk",
  "water-warrior",
  "divine-sword-warrior",
  "warrior",
  "steel-armor-warrior",
  "priest",
  "wizard",
  "magic-master",
  "evil-sword-warrior",
  "engineer",
  "empress",
  "dragon",
  "head",
  "hand",
];

const [unitCatalog, mapRules, promotionTable, campaignRoster] = await Promise.all([
  readFile(unitCatalogPath, "utf8").then(JSON.parse),
  readFile(mapRulesPath, "utf8").then(JSON.parse),
  readFile(promotionTablePath, "utf8").then(JSON.parse),
  readFile(campaignRosterPath, "utf8").then(JSON.parse),
]);

if (unitCatalog.records.length !== 39 || mapRules.records.length !== 39 || CLASS_IDS.length !== 39) {
  throw new Error("class catalog generation requires exactly 39 aligned native records");
}

const mapRuleByRecord = new Map(mapRules.records.map((record) => [record.record, record]));
const fallbackPortraitByCode = new Map(
  campaignRoster.displayResolution.classFallbacks.map((fallback) => [
    fallback.classCode,
    fallback.portraitRecord,
  ]),
);
const idByRecord = Object.fromEntries(CLASS_IDS.map((id, record) => [record, id]));

/**
 * `1N/半龍戰士` is in the native 技術 menu chain but has no DS:41CE tier table;
 * its single technique lives in a dedicated handler with no action code and no
 * submenu. Project only the rule-bearing numbers so native addresses stay in
 * the evidence layer.
 */
function normalizeDirectTechnique(direct) {
  if (!direct) return null;
  if (direct.visibleActionCode !== null || direct.submenu !== null) {
    throw new Error(`${direct.classCode}: direct technique unexpectedly carries menu content`);
  }
  return {
    classCode: direct.classCode,
    rangeSeed: direct.range.seed,
    rangePropagationMode: direct.range.mode,
    target: "empty-cell",
    endsActivation: direct.commit.followUpAttack === false,
    grantsExperience: direct.commit.experience !== null,
  };
}
const catalog = Object.fromEntries(unitCatalog.records.map((record, expectedRecord) => {
  if (record.record !== expectedRecord) {
    throw new Error(`unit catalog record ${record.record} is out of order at ${expectedRecord}`);
  }
  const id = CLASS_IDS[record.record];
  const mapRule = mapRuleByRecord.get(record.record);
  if (!mapRule || mapRule.name !== record.name) {
    throw new Error(`map rules are not aligned for native class ${record.record}`);
  }
  return [id, {
    id,
    nativeRecord: record.record,
    nativeName: record.name,
    recordKind: record.recordKind,
    codes: record.codes,
    genericPortraitRecord: fallbackPortraitByCode.get(record.codes.side1) ?? null,
    actionCategory: record.playerActionCategory,
    aiClassDispatch: record.aiClassDispatch,
    dataRows: record.dataRows,
    postThirdRowGrowth: record.postThirdRowGrowth,
    killRewards: record.killRewards,
    ordinaryHitStatuses: record.ordinaryHitStatuses,
    shooting: record.shooting,
    technique: record.technique,
    directTechnique: normalizeDirectTechnique(record.directTechnique),
    movementProfile: record.mapRules.movementProfile,
    terrainDefenseProfile: record.mapRules.terrainDefenseProfile,
    movementRules: mapRule.movementRules,
    terrainDefensePercents: mapRule.terrainDefensePercents,
    promotion: {
      triggerGrowthRow: record.promotion.triggerGrowthRow,
      triggerExperienceThreshold: record.promotion.triggerExperienceThreshold,
      dataRow4Level: record.promotion.dataRow4Level,
      dataRow4ExperienceThreshold: record.promotion.dataRow4ExperienceThreshold,
      targets: record.promotion.targets.map((target) => ({
        id: idByRecord[target.record],
        nativeRecord: target.record,
        optionIndex: target.optionIndex,
        targetStartLevel: target.targetStartLevel,
      })),
    },
  }];
}));

const source = `// Generated by scripts/generate-class-catalog.mjs from reverse/parsed/native/unit-catalog.json,\n` +
  `// reverse/parsed/native/map-rules.json, and reverse/parsed/native/campaign-roster.json. Do not hand-edit.\n` +
  `export const CLASS_IDS = ${JSON.stringify(CLASS_IDS, null, 2)} as const;\n\n` +
  `export type ClassId = typeof CLASS_IDS[number];\n\n` +
  `export const CLASS_CATALOG = ${JSON.stringify(catalog, null, 2)} as const;\n\n` +
  `export const CLASS_ID_BY_NATIVE_RECORD = ${JSON.stringify(idByRecord, null, 2)} as const;\n`;

await writeFile(outputPath, source, "utf8");

const promotionDialogue = promotionTable.runtimeEvidence?.promotionDialogue;
const niaQuestion = promotionDialogue?.niaSequence?.[0]?.lines;
const teammateRequest = promotionDialogue?.teammateSequence?.[0]?.lines;
const niaGrant = promotionDialogue?.teammateSequence?.[1]?.lines;
const upperTextInset = promotionDialogue?.textInsets?.upper?.inset;
const lowerTextInset = promotionDialogue?.textInsets?.lower?.inset;
if (
  promotionDialogue?.niaCharacterRecord !== 0x2e
  || !Array.isArray(niaQuestion)
  || !Array.isArray(teammateRequest)
  || !Array.isArray(niaGrant)
  || !Array.isArray(upperTextInset)
  || !Array.isArray(lowerTextInset)
  || upperTextInset.length !== 2
  || lowerTextInset.length !== 2
  || !upperTextInset.every(Number.isInteger)
  || !lowerTextInset.every(Number.isInteger)
) {
  throw new Error("promotion dialogue generation requires the verified 0000:0487 evidence");
}
const promotionDialogueSource =
  "// Generated by scripts/generate-class-catalog.mjs from " +
  "reverse/parsed/native/promotion-table.json. Do not hand-edit.\n" +
  `export const NIA_CHARACTER_RECORD = ${promotionDialogue.niaCharacterRecord} as const;\n\n` +
  `export const PROMOTION_DIALOGUE_TEXT = ${JSON.stringify({
    niaQuestion: niaQuestion.join("\n"),
    niaGrant: niaGrant.join("\n"),
    teammateRequest: teammateRequest.join("\n"),
  }, null, 2)} as const;\n\n` +
  `export const PROMOTION_DIALOGUE_TEXT_INSETS = ${JSON.stringify({
    upper: { x: upperTextInset[0], y: upperTextInset[1] },
    lower: { x: lowerTextInset[0], y: lowerTextInset[1] },
  }, null, 2)} as const;\n`;
await writeFile(promotionDialogueOutputPath, promotionDialogueSource, "utf8");

console.log(
  `wrote ${path.relative(root, outputPath)} (${CLASS_IDS.length} classes) and ` +
  path.relative(root, promotionDialogueOutputPath),
);
