    @Override
    protected void run() throws Exception {
        String programName = currentProgram.getName();
        String[][] functions;
        if (programName.equals("0021-unpacked.bin")) {
            functions = MODULE_21;
        }
        else if (programName.equals("0023-unpacked.bin")) {
            functions = MODULE_23;
        }
        else if (programName.equals("0025-unpacked.bin")) {
            functions = MODULE_25;
        }
        else if (programName.equals("0027-unpacked.bin")) {
            functions = MODULE_27;
        }
        else if (programName.equals("0029-unpacked.bin")) {
            functions = MODULE_29;
        }
        else if (programName.equals("0033-unpacked.bin")) {
            functions = MODULE_33;
        }
        else if (programName.equals("0035-unpacked.bin")) {
            functions = MODULE_35;
        }
        else if (programName.equals("0046-unpacked.bin")) {
            functions = MODULE_46;
        }
        else if (programName.equals("JS3.UNPACKED.EXE")) {
            functions = JS3;
        }
        else {
            println("No known runtime-function labels for " + programName);
            return;
        }

        for (String[] spec : functions) {
            markFunction(spec[0], spec[1]);
        }
        println("Marked " + functions.length + " known functions in " + programName);
    }

    private void markFunction(String addressText, String name) throws Exception {
        Address address = currentProgram.getAddressFactory().getAddress(addressText);
        if (address == null || !currentProgram.getMemory().contains(address)) {
            throw new IllegalArgumentException("Address outside program: " + addressText);
        }
        if (getInstructionAt(address) == null) {
            disassemble(address);
        }
        Function function = getFunctionAt(address);
        if (function == null) {
            function = createFunction(address, name);
        }
        if (function == null) {
            throw new IllegalStateException("Could not create function at " + addressText);
        }
        if (!function.getName().equals(name)) {
            function.setName(name, SourceType.USER_DEFINED);
        }
        createLabel(address, name, true);
    }
