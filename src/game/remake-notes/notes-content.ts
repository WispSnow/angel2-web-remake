/**
 * 「複刻說明」面板的策展文字。
 *
 * 每一條都對應 `reverse/gdd/web-remake-rule-decisions.md` 的一個 `REMAKE-0xx` 決定，
 * 只是把該決定寫成玩家讀得懂的一句話。這裡不是真值來源：規則以決定記錄與
 * `src/game/simulation/` 的實現為準，本檔只負責敘述。新增或修改條目時同時更新對應
 * 決定編號，避免面板與決策記錄漂移。
 *
 * **這些字串會隨遊戲本體發行，而 `reverse/`、`design/` 與決定記錄不會。** 因此面板上
 * 看得到的文字裡不得出現倉庫路徑、文件名、`[OF]/[DD]/[SR]` 證據標籤，也不得出現
 * `stableRemake`／`legacyStrict` 這類玩家在遊戲裡選不到的規則集代號——玩家沒有那些
 * 東西，寫出來只會製造困惑。要備忘出處就寫在原始碼註解裡（就像這一段）。同理，條目
 * 之間互相引用時只能引用**同一個面板裡真的看得到**的條目：`REMAKE-102` 沒有進面板，
 * 所以 `REMAKE-116` 的內文不提它的編號。原版自身的記錄號、資源名與位址（`A/17`、
 * `MAGIC/20`、`0000:9252`…）不在此限——那是原版的內容，不是本專案的文件。
 *
 * 分類界線：
 * - `BUG_FIX_SECTION` 只收「原版確實壞掉、複刻修好」的條目；
 * - `FEATURE_SECTION` 收不改變合法操作與結算的資訊、表現與操作增強——玩家看得更清楚，
 *   但同一組操作打出同一個結果；
 * - `BALANCE_SECTION` 收 `[DD]` 產品決定——原版沒壞，是複刻主動改了手感。
 *
 * 一條決定同時有規則面與顯示面時，按玩家實際感受到的那一面歸類：`REMAKE-101` 只是在
 * 提交前把範圍畫出來、沒有動冰雪的任何判定，所以歸「功能增強」；`REMAKE-035` 改變了誰
 * 會中箭，所以留在「平衡性調整」。
 *
 * **面板只比對「原版怎麼樣」與「複刻現在怎麼樣」，不敘述複刻自己走過的路。** 「複刻此前……
 * 現已改為」「曾試過 X，試玩後收回」「另一個方案被否決」都是開發過程，玩家沒有經歷過那些
 * 版本，寫出來只是噪音。同理，複刻自己寫壞又貼回原版的修正在這裡等於「原版與複刻相同」，
 * 沒有可比對的差異，不該立條目——`REMAKE-105`（被友軍占據的敵方鄰格不是終止格）因此不收。
 * 「目前已實裝關卡」這種透露開發進度的說法同樣不寫進面板。
 *
 * 「這一條沒有動 X」這種話一律**只說本條**，不要寫成「X 一行未動」——冰雪就是反例：
 * `REMAKE-101`／`REMAKE-034` 各自沒動冰雪判定，但冰雪本身已經被 `REMAKE-013`／`094`／`096`
 * 改過三輪，寫成全稱句就和同一個面板上的條目互相矛盾。同理，凡是拿「原版數值」當對照的
 * 句子（例如某難度「完全不變」），改動別條決定時要回來重算——`REMAKE-103` 把難度 1／2 的
 * 出場等級推過固定三行之後，`REMAKE-092` 原本寫的「難度 0／1 不變」就只剩難度 0 成立。
 *
 * 「功能增強」有一部分條目沒有決定編號：純顯示、不動規則的增強登記在設計文件的 `[DD]`
 * 段落而不是規則決定記錄——介面增強在 `design/remake-gdd/07-ui-ux-and-presentation.md`，
 * 存檔與流程在 `design/remake-gdd/02-game-flow.md`。這類條目設 `badge: false`，`id` 直接
 * 用一個短 slug 當識別碼、面板不畫徽章；不要為它們發明新的編號體系，也不要把設計文件的
 * 章節號當成編號印給玩家看。
 *
 * 刻意不收的決定（新增條目前先讀這一段，不要「補回來」）：
 * - `REMAKE-002`／`REMAKE-003`：修的是原生 AI 的缺陷，但 `REMAKE-033` 已把整個規劃器換成
 *   專家 AI，這兩條在預設規則集下不再單獨可見；
 * - `REMAKE-054`：琴斯的職業是**複刻自己**把勝利登場硬寫成士兵造成的，原版事件根本沒在
 *   該指令寫職業，不存在這個問題，因此不是原版 bug；
 * - `REMAKE-010`：`D/59` 眼位是原版資料錯誤，但「為什麼在發行版看不到」牽涉一處未解決的
 *   文件衝突——`reverse/notes/unit-detail-hud-presentations.md` 與 `original-gdd.md` 都說
 *   戰鬥右欄只繪 frame 0（面板還會整頁快取），`design/remake-gdd/07-ui-ux-and-presentation.md`
 *   卻標 `[OF]` 說右欄也會眨眼。衝突閉合前不對玩家宣稱它的成因。
 */

export interface RemakeNote {
  /** 條目識別碼；有決定編號時就直接用編號，面板同時把它畫成徽章。 */
  readonly id: string;
  /** 一個決定拆成多條時的穩定識別碼；省略時等於 `id`。 */
  readonly slug?: string;
  /**
   * 純顯示增強沒有規則決定編號，設 `false` 讓面板只用 `id` 做識別、不畫徽章。
   * 發行版沒有決定記錄，畫一個玩家查不到的編號只會製造困惑。
   */
  readonly badge?: false;
  readonly title: string;
  readonly tags: readonly string[];
  readonly original: string;
  readonly remake: string;
  readonly impact?: string;
}

export interface RemakeNoteGroup {
  readonly id: string;
  readonly title: string;
  readonly summary: string;
  readonly notes: readonly RemakeNote[];
}

export interface RemakeNoteSection {
  readonly intro: string;
  readonly groups: readonly RemakeNoteGroup[];
}

